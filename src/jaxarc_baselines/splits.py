"""Seeded task splits written as JaxARC subset files.

Tasks that share an input/output pair, or share a title (the task id without
its trailing random id, case and variant marks such as ``_2`` or ``_edit``), are
kept in the same split, so a near-copy of a dev or
test task can't sit in train. Groups are placed in a fixed order drawn from the
seed, so the split depends only on the task contents and the seed.

Regenerate the MiniARC split with::

    python -m jaxarc_baselines.splits data/MiniARC/data/MiniARC configs/env/jaxarc/subsets/Mini

which writes ``split_{train,dev,test}.yaml``, used as ``Mini-split_train`` etc.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

import numpy as np
import yaml

MINIARC_SEED = 20261112
MINIARC_SIZES = {"test": 30, "dev": 30}  # the rest is train (89 of 149)
# MiniARC marks reworked copies of a task with these; ``Emcoding`` is a typo of ``encoding``.
_VARIANT_PREFIX = re.compile(r"^edit_+")
_VARIANT_SUFFIX = re.compile(r"(_+(edit|corrected|updated|\d+))+$")
_TYPOS = {"emcoding": "encoding"}


def task_title(task_id: str) -> str:
    """The task's family name: the id without its random suffix, case or variant marks.

    ``One_Color_gravity_2_l6b...`` and ``One_Color_Gravity_l6b...`` -> ``one_color_gravity``.
    """
    title = task_id.rsplit("_", 1)[0].lower()
    title = _VARIANT_SUFFIX.sub("", _VARIANT_PREFIX.sub("", title))
    for typo, fixed in _TYPOS.items():
        title = title.replace(typo, fixed)
    return title


def pair_hash(pair: dict) -> str:
    return hashlib.sha1(json.dumps([pair["input"], pair["output"]]).encode()).hexdigest()


def task_groups(tasks: dict[str, list[dict]]) -> list[list[str]]:
    """Tasks linked by a shared pair or a shared title, as sorted groups."""
    parent = {t: t for t in tasks}

    def find(t: str) -> str:
        while parent[t] != t:
            parent[t] = parent[parent[t]]
            t = parent[t]
        return t

    first_seen: dict[str, str] = {}
    for task in sorted(tasks):
        keys = [f"title:{task_title(task)}"] + [f"pair:{pair_hash(p)}" for p in tasks[task]]
        for key in keys:
            other = first_seen.setdefault(key, task)
            parent[find(other)] = find(task)

    groups: dict[str, list[str]] = {}
    for task in sorted(tasks):
        groups.setdefault(find(task), []).append(task)
    return sorted(groups.values())


def split_tasks(
    tasks: dict[str, list[dict]], sizes: dict[str, int], seed: int
) -> dict[str, list[str]]:
    """Fill each named split in ``sizes`` order with whole groups; the rest is train.

    A group that doesn't fit the split being filled goes to the next one, so the
    sizes are exact unless groups make that impossible.
    """
    groups = task_groups(tasks)
    order = np.random.default_rng(seed).permutation(len(groups))
    split: dict[str, list[str]] = {name: [] for name in sizes}
    split["train"] = []
    for i in order:
        group = groups[i]
        target = next(
            (name for name, n in sizes.items() if len(split[name]) + len(group) <= n),
            "train",
        )
        split[target].extend(group)
    return {"train": sorted(split.pop("train")), **{k: sorted(v) for k, v in split.items()}}


def load_tasks(directory: str | Path) -> dict[str, list[dict]]:
    """Task id -> all pairs (train and test) from a folder of ARC JSON files."""
    tasks = {}
    for path in sorted(Path(directory).glob("*.json")):
        data = json.loads(path.read_text())
        tasks[path.stem] = data["train"] + data["test"]
    return tasks


def write_subsets(split: dict[str, list[str]], directory: str | Path, header: str) -> None:
    """Write ``split_<name>.yaml`` subset files, one per split."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    for name, ids in split.items():
        comment = "".join(f"# {line}\n" for line in header.splitlines())
        body = yaml.safe_dump({"task_ids": ids}, default_flow_style=False, sort_keys=False)
        (directory / f"split_{name}.yaml").write_text(comment + body)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("tasks", help="folder of MiniARC task JSON files")
    parser.add_argument("out", help="subset folder, e.g. configs/env/jaxarc/subsets/Mini")
    args = parser.parse_args()

    tasks = load_tasks(args.tasks)
    split = split_tasks(tasks, MINIARC_SIZES, seed=MINIARC_SEED)
    counts = ", ".join(f"{k} {len(v)}" for k, v in split.items())
    header = (
        f"MiniARC task split ({counts} of {len(tasks)}), seed {MINIARC_SEED}.\n"
        "Generated by `python -m jaxarc_baselines.splits`; don't edit by hand.\n"
        "Tasks sharing a pair or a title are in the same split."
    )
    write_subsets(split, args.out, header)
    print(counts)


if __name__ == "__main__":
    main()
